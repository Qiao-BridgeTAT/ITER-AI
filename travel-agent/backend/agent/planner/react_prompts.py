def agent_system_prompt(source: Literal["planner", "reviewer"], tool_names: Iterable[str]) -> str:
    """Never advertise a withheld tool, including after budget/authority filtering."""
    names = set(tool_names)
    guide = []
    for group, title, purpose in _CAPABILITIES:
        present = names & group
        if present:
            guide.append(f"- {title}（{'、'.join(sorted(present))}）：{purpose}")
            names -= present
    if names:
        guide.append(f"- 其他工具（{'、'.join(sorted(names))}）：用途及参数见各工具定义。")
    base = PLANNER_SYSTEM if source == "planner" else REVIEWER_SYSTEM
    return base + "\n" + DAY_BALANCE_EXAMPLES + "\n## 本轮可用工具\n" + "\n".join(guide)
